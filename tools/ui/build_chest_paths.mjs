import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
const root = process.cwd();
function loadArt(folder) {
  const source=path.join(root,'docs/design/2026-10-22',folder);
  const context=vm.createContext({});
  vm.runInContext(fs.readFileSync(path.join(source,'pen.js'),'utf8'),context);
  let art=fs.readFileSync(path.join(source,'chest.js'),'utf8');
  const replace=(from,to)=>{
    if(!art.includes(from))throw Error(`Approved ${folder} source marker changed: ${from}`);
    art=art.replace(from,to);
  };
  replace('    P.save();\n    P.translate(12*open,-53*open); P.rotate(-15*open);',
    '    P.beginLayer("lid"); P.save();');
  replace('    P.restore();\n    // A cat-head latch',
    '    P.restore(); P.beginLayer("latch");\n    // A cat-head latch');
  replace('    if (open > 0) P.shape(Pen.rrect(-104,-18,208,37,13),{fill:C.cavity,stroke:C.ink,width:MAIN});',
    '    if (open > 0) { P.beginLayer("mouth"); P.shape(Pen.rrect(-104,-18,208,37,13),{fill:C.cavity,stroke:C.ink,width:MAIN}); P.beginLayer("body"); }');
  vm.runInContext(art,context);
  const{Pen,ChestPilot}=context;
  class LayerPen extends Pen {
    constructor(){super();this.layer='body';}
    beginLayer(name){this.layer=name;}
    shape(cmds,style){super.shape(cmds,style);this.ops.at(-1).layer=this.layer;}
  }
  const roles=Object.fromEntries(Object.entries(ChestPilot.colors).map(([key,color])=>
    [color,{ink:'ink',wood:'body',end:'dark',inset:'inset',grain:'surface',brass:'band',fold:'band_fold',brassInk:'band_ink',cavity:'cavity'}[key]||key]));
  return {Pen,ChestPilot,LayerPen,roles};
}
const basic=loadArt('chest-polish');
const premium=loadArt('chest-premium');
const round = x => +x.toFixed(4);
const pt = (x,y) => [round(x),round(y)];
function flatten(d) {
  const tokens = d.match(/[MLQCZ]|-?\d+(?:\.\d+)?/g);
  const points = [], joins = [];
  let i=0, from, first;
  while(i<tokens.length) {
    const cmd=tokens[i++];
    const number=()=>+tokens[i++];
    if(cmd==='M' || cmd==='L') {
      from=pt(number(),number()); if(!first) first=from;
      points.push(from); joins.push(from);
    } else if(cmd==='Q') {
      const control=pt(number(),number()), to=pt(number(),number());
      for(let step=1;step<=12;step++) {
        const t=step/12,u=1-t;
        points.push(pt(u*u*from[0]+2*u*t*control[0]+t*t*to[0],u*u*from[1]+2*u*t*control[1]+t*t*to[1]));
      }
      from=to; joins.push(to);
    } else if(cmd==='C') {
      const a=pt(number(),number()),b=pt(number(),number()),to=pt(number(),number());
      for(let step=1;step<=16;step++) {
        const t=step/16,u=1-t;
        points.push(pt(u*u*u*from[0]+3*u*u*t*a[0]+3*u*t*t*b[0]+t*t*t*to[0],u*u*u*from[1]+3*u*u*t*a[1]+3*u*t*t*b[1]+t*t*t*to[1]));
      }
      from=to; joins.push(to);
    } else if(cmd==='Z') {
      if(points.at(-1)[0]!==first[0] || points.at(-1)[1]!==first[1]) points.push(first);
      from=first;
    } else throw Error(`Unsupported path command ${cmd}`);
  }
  return {points,joins};
}
const data={};
for(const [tier,art] of [['basic',basic],['gold',premium]]) {
for(const small of [false,true]) {
  const suffix=small?'small':'full';
  for(const open of [0,1]) {
    const pen=new art.LayerPen(); art.ChestPilot.chest(pen,open,small);
    const layers={};
    for(const op of pen.ops) {
      const item={...flatten(op.d),fill:op.fill?art.roles[op.fill]:'',stroke:op.stroke?art.roles[op.stroke]:'',width:op.width};
      if((op.fill && !item.fill)||(op.stroke && !item.stroke)) throw Error(`Unmapped ink ${JSON.stringify(op)}`);
      (layers[op.layer] ||= []).push(item);
    }
    data[`${tier}_${suffix}_${open?'open':'closed'}`]=layers;
  }
}
}
